// Emits sw.js, a small service worker that precaches every file of the build.
// Once the Hall has loaded, the whole site (every lazy simulation chunk and
// every font) keeps working with the network switched off. There is nothing
// else to fetch: the site never asks another origin for anything.
import type { Plugin } from 'vite';

const CACHE_PREFIX = 'omy-';

export function offlinePrecache(): Plugin {
  return {
    name: 'one-more-year:offline-precache',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle)
        .filter((file) => !file.endsWith('.map'))
        .sort();
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(files, hashFileList(files)),
      });
    },
  };
}

function hashFileList(files: readonly string[]): string {
  // Built file names already carry content hashes, so hashing the list is
  // enough to give each deploy its own cache.
  let hash = 0x811c9dc5;
  for (const char of files.join('|')) {
    hash ^= char.charCodeAt(0);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
}

function serviceWorkerSource(files: readonly string[], version: string): string {
  const precache = JSON.stringify(['./', ...files.map((file) => `./${file}`)]);
  return `// Generated by hall/build/offline-precache.ts. Do not edit.
const CACHE = '${CACHE_PREFIX}${version}';
const PRECACHE = ${precache};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('${CACHE_PREFIX}') && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  // Pages: network first so a new deploy shows up, the cached shell when offline.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./', { ignoreSearch: true })));
    return;
  }
  // Hashed assets never change, so a cache hit is always right.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;
}
